def _expected_view(expected):
    """Project the legacy expected batch onto the HCM output field names."""
    view = []
    for r in expected["records"]:
        view.append({
            "txn_id": r["txn_id"],
            "customer_id": r["customer_in"],
            "cruise_id": r["cruise_in"],
            "booking_date": r["booking_date"],
            "outcome": r["outcome"],
            "message_code": r["msg_nr"],
            "contract_id": r["contract_id"],
            "price": Decimal(r["price"]) if r["price"] is not None else None,
            "availability_after": r["availability_after"],
        })
    return view


def _fmt(value, decimals=None):
    if value is None:
        return ""
    if isinstance(value, Decimal) and decimals is not None:
        return str(lb.cents(value, decimals))
    return str(value)


def _totals(records, decimals):
    accepted = [r for r in records if r["outcome"] == lb.ACCEPTED]
    by_msg = {}
    for r in records:
        key = str(r["message_code"])
        by_msg[key] = by_msg.get(key, 0) + 1
    price_sum = sum((lb.cents(r["price"], decimals) for r in accepted
                     if r["price"] is not None), Decimal(0))
    ids = [r["contract_id"] for r in accepted if r["contract_id"] is not None]
    accepted_per_cruise = {}
    for r in accepted:
        key = r["cruise_id"].strip()
        accepted_per_cruise[key] = accepted_per_cruise.get(key, 0) + 1
    return {
        "record_count": len(records),
        "accepted_count": len(accepted),
        "rejected_count": len(records) - len(accepted),
        "count_by_msg_nr": dict(sorted(by_msg.items())),
        "price_sum": str(lb.cents(price_sum, decimals)),
        "contract_id_count": len(ids),
        "distinct_contract_id_count": len(set(ids)),
        "accepted_per_cruise": dict(sorted(accepted_per_cruise.items())),
    }


def reconcile(expected, hcm_records, decimals=2, tolerance_cents=0):
    """Compare the HCM output with the legacy expected batch.

    Returns (summary, audit_rows, exceptions). Every expected transaction
    gets one audit row; every finding gets one exception row with a check
    identifier documented in equivalence-approach.md.
    """
    exp_rows = _expected_view(expected)
    exp_by_id = {r["txn_id"]: r for r in exp_rows}
    act_by_id = {r["txn_id"]: r for r in hcm_records}
    tolerance = Decimal(tolerance_cents).scaleb(-2)
    exceptions = []
    audit = []

    def add_exc(check, txn_id, field, expected_v, actual_v, detail):
        exceptions.append({
            "check": check,
            "txn_id": txn_id,
            "field": field,
            "expected": expected_v,
            "actual": actual_v,
            "detail": detail,
        })

    # -- control totals ----------------------------------------------------
    exp_totals = expected["control_totals"]
    act_totals = _totals(hcm_records, decimals)
    exp_price_sum = Decimal(exp_totals["price_sum"])
    act_price_sum = Decimal(act_totals["price_sum"])
    ct = [
        ("CT-01", "record_count", exp_totals["record_count"],
         act_totals["record_count"]),
        ("CT-02", "accepted_count", exp_totals["accepted_count"],
         act_totals["accepted_count"]),
        ("CT-02", "rejected_count", exp_totals["rejected_count"],
         act_totals["rejected_count"]),
    ]
    for check, field, e, a in ct:
        if e != a:
            add_exc(check, "*", field, str(e), str(a),
                    f"batch {field} differs by {a - e:+d}")
    codes = sorted(set(exp_totals["count_by_msg_nr"])
                   | set(act_totals["count_by_msg_nr"]), key=int)
    for code in codes:
        e = exp_totals["count_by_msg_nr"].get(code, 0)
        a = act_totals["count_by_msg_nr"].get(code, 0)
        if e != a:
            add_exc("CT-03", "*", f"count_by_msg_nr[{code}]", str(e), str(a),
                    f"message code {code} occurrences differ by {a - e:+d}")
    if abs(act_price_sum - exp_price_sum) > tolerance:
        diff_cents = int(((act_price_sum - exp_price_sum) * 100)
                         .to_integral_value())
        add_exc("CT-04", "*", "price_sum", str(exp_price_sum),
                str(act_price_sum),
                f"sum of PRICE over accepted records differs by "
                f"{diff_cents:+d} cent(s)")
    if act_totals["distinct_contract_id_count"] != act_totals[
            "contract_id_count"]:
        add_exc("CT-05", "*", "distinct_contract_id_count",
                str(act_totals["contract_id_count"]),
                str(act_totals["distinct_contract_id_count"]),
                "CONTRACT_ID values in the HCM output are not unique")
    before = expected["availability_before"]
    exp_delta = exp_totals["availability_delta"]
    for cruise in sorted(before, key=int):
        e_delta = exp_delta[cruise]
        a_delta = -act_totals["accepted_per_cruise"].get(cruise, 0)
        if e_delta != a_delta:
            add_exc("CT-06", "*", f"availability_delta[{cruise}]",
                    str(e_delta), str(a_delta),
                    f"cruise {cruise}: accepted bookings imply availability "
                    f"delta {a_delta:+d}, legacy {e_delta:+d}")

    # -- record level --------------------------------------------------------
    field_checks = [
        ("RL-03", "outcome"),
        ("RL-04", "message_code"),
        ("RL-05", "contract_id"),
        ("RL-06", "price"),
        ("RL-07", "availability_after"),
    ]
    for txn_id in sorted(exp_by_id):
        e = exp_by_id[txn_id]
        a = act_by_id.get(txn_id)
        row = {
            "txn_id": txn_id,
            "customer_id": e["customer_id"],
            "cruise_id": e["cruise_id"],
            "expected_outcome": e["outcome"],
            "expected_message_code": e["message_code"],
            "expected_contract_id": _fmt(e["contract_id"]),
            "expected_price": _fmt(e["price"], decimals),
            "expected_availability_after": _fmt(e["availability_after"]),
        }
        if a is None:
            row.update({
                "actual_outcome": "", "actual_message_code": "",
                "actual_contract_id": "", "actual_price": "",
                "actual_availability_after": "", "price_diff_cents": "",
                "status": "MISSING", "checks_failed": "RL-01",
            })
            add_exc("RL-01", txn_id, "record", "present", "absent",
                    f"transaction {txn_id} (customer '{e['customer_id']}', "
                    f"cruise '{e['cruise_id']}') absent from HCM output")
            audit.append(row)
            continue
        failed = []
        for check, field in field_checks:
            ev, av = e[field], a[field]
            if field == "price":
                if ev is None and av is None:
                    continue
                if ev is None or av is None:
                    failed.append(check)
                    add_exc(check, txn_id, field, _fmt(ev, decimals),
                            _fmt(av, decimals),
                            "PRICE present on one side only")
                    continue
                diff = lb.cents(av, decimals) - lb.cents(ev, decimals)
                if abs(diff) > tolerance:
                    failed.append(check)
                    diff_cents = int((diff * 100).to_integral_value())
                    add_exc(check, txn_id, field, _fmt(ev, decimals),
                            _fmt(av, decimals),
                            f"PRICE differs by {diff_cents:+d} cent(s)")
            elif ev != av:
                failed.append(check)
                add_exc(check, txn_id, field, _fmt(ev), _fmt(av),
                        f"{field} differs")
        price_diff = ""
        if e["price"] is not None and a["price"] is not None:
            price_diff = str(int(((lb.cents(a["price"], decimals)
                                   - lb.cents(e["price"], decimals)) * 100)
                                 .to_integral_value()))
        row.update({
            "actual_outcome": a["outcome"],
            "actual_message_code": a["message_code"],
            "actual_contract_id": _fmt(a["contract_id"]),
            "actual_price": _fmt(a["price"], decimals),
            "actual_availability_after": _fmt(a["availability_after"]),
            "price_diff_cents": price_diff,
            "status": "MATCH" if not failed else "MISMATCH",
            "checks_failed": ";".join(failed),
        })
        audit.append(row)
    for txn_id in sorted(set(act_by_id) - set(exp_by_id)):
        a = act_by_id[txn_id]
        add_exc("RL-02", txn_id, "record", "absent", "present",
                f"transaction {txn_id} in HCM output has no legacy "
                "counterpart")
        audit.append({
            "txn_id": txn_id, "customer_id": a["customer_id"],
            "cruise_id": a["cruise_id"], "expected_outcome": "",
            "expected_message_code": "", "expected_contract_id": "",
            "expected_price": "", "expected_availability_after": "",
            "actual_outcome": a["outcome"],
            "actual_message_code": a["message_code"],
            "actual_contract_id": _fmt(a["contract_id"]),
            "actual_price": _fmt(a["price"], decimals),
            "actual_availability_after": _fmt(a["availability_after"]),
            "price_diff_cents": "", "status": "UNEXPECTED",
            "checks_failed": "RL-02",
        })

    # -- cross-record integrity ----------------------------------------------
    owners = {}
    for r in hcm_records:
        if r["outcome"] == lb.ACCEPTED and r["contract_id"] is not None:
            owners.setdefault(r["contract_id"], []).append(r["txn_id"])
    pre_existing = set(expected["pre_existing_contract_ids"])
    for contract_id in sorted(owners):
        txns = owners[contract_id]
        if len(txns) > 1:
            add_exc("IN-01", ";".join(txns), "contract_id", "unique",
                    str(contract_id),
                    f"CONTRACT_ID {contract_id} assigned to "
                    f"{len(txns)} transactions")
        if contract_id in pre_existing:
            add_exc("IN-02", ";".join(txns), "contract_id",
                    f"> {max(pre_existing)}", str(contract_id),
                    "CONTRACT_ID collides with a contract that existed "
                    "before the batch")
    for cruise in sorted(before, key=int):
        accepted_n = act_totals["accepted_per_cruise"].get(cruise, 0)
        if accepted_n > before[cruise]:
            txns = [r["txn_id"] for r in hcm_records
                    if r["outcome"] == lb.ACCEPTED
                    and r["cruise_id"].strip() == cruise]
            add_exc("IN-03", ";".join(txns), "availability",
                    f"<= {before[cruise]} accepted", f"{accepted_n} accepted",
                    f"cruise {cruise} oversold: {accepted_n} bookings "
                    f"accepted against {before[cruise]} available")
    customer_master = {
        str(rec["PERSON-ID"])
        for rec in lb.build_db().files["NCCUSTOMER"].records.values()}
    for r in hcm_records:
        if r["outcome"] == lb.ACCEPTED and (
                r["customer_id"].strip() not in customer_master):
            add_exc("IN-04", r["txn_id"], "customer_id", "in NCCUSTOMER",
                    r["customer_id"],
                    f"booking accepted for customer '{r['customer_id']}' who "
                    "is not in the synthetic customer master")

    exceptions.sort(key=lambda x: (x["check"], x["txn_id"], x["field"]))
    summary = {
        "harness_version": HARNESS_VERSION,
        "batch_id": expected["batch_id"],
        "decimals": decimals,
        "tolerance_cents": tolerance_cents,
        "result": "RECONCILED" if not exceptions else "EXCEPTIONS",
        "exception_count": len(exceptions),
        "exceptions_by_check": _count_by(exceptions, "check"),
        "records_expected": len(exp_rows),
        "records_actual": len(hcm_records),
        "records_matched": sum(1 for r in audit if r["status"] == "MATCH"),
        "records_mismatched": sum(
            1 for r in audit if r["status"] == "MISMATCH"),
        "records_missing": sum(1 for r in audit if r["status"] == "MISSING"),
        "records_unexpected": sum(
            1 for r in audit if r["status"] == "UNEXPECTED"),
        "control_totals": {
            "legacy_expected": exp_totals,
            "hcm_output": act_totals,
            "price_sum_diff_cents": int(
                ((act_price_sum - exp_price_sum) * 100).to_integral_value()),
        },
    }
    return summary, audit, exceptions


def _count_by(rows, key):
    out = {}
    for r in rows:
        out[r[key]] = out.get(r[key], 0) + 1
    return dict(sorted(out.items()))


