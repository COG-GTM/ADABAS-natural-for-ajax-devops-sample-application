def _int_or_none(value, field, row_no, lo, hi):
    if value is None or str(value).strip() == "":
        return None
    text = str(value).strip()
    if not re.fullmatch(r"-?\d{1,10}", text):
        raise LayoutError(f"row {row_no}: {field} '{text}' is not an integer")
    number = int(text)
    if not lo <= number <= hi:
        raise LayoutError(
            f"row {row_no}: {field} {number} outside {lo}..{hi}")
    return number


def _decimal_or_none(value, field, row_no):
    if value is None or str(value).strip() == "":
        return None
    text = str(value).strip()
    if not re.fullmatch(r"-?\d{1,10}(\.\d{1,3})?", text):
        raise LayoutError(
            f"row {row_no}: {field} '{text}' is not a decimal with at most "
            "10 integer and 3 fraction digits (DDM PRICE is P 10.3)")
    try:
        return Decimal(text)
    except InvalidOperation as exc:  # pragma: no cover - regex guards this
        raise LayoutError(f"row {row_no}: {field} '{text}' invalid") from exc


def _normalise_record(raw, row_no):
    txn_id = str(raw.get("txn_id", "")).strip()
    if not TXN_ID_RE.match(txn_id):
        raise LayoutError(
            f"row {row_no}: TXN_ID '{txn_id}' must match {TXN_ID_RE.pattern}")
    customer_id = str(raw.get("customer_id", "") or "")
    cruise_id = str(raw.get("cruise_id", "") or "")
    for field, value in (("CUSTOMER_ID", customer_id),
                         ("CRUISE_ID", cruise_id)):
        if not INPUT_RE.match(value):
            raise LayoutError(
                f"row {row_no}: {field} '{value}' must be 0-8 alphanumeric "
                "characters (A8 input parameter)")
    outcome = str(raw.get("outcome", "")).strip().upper()
    if outcome not in OUTCOMES:
        raise LayoutError(
            f"row {row_no}: OUTCOME '{outcome}' not in {sorted(OUTCOMES)}")
    message_code = _int_or_none(raw.get("message_code"), "MESSAGE_CODE",
                                row_no, 0, 9999)
    if message_code is None:
        raise LayoutError(f"row {row_no}: MESSAGE_CODE is required")
    return {
        "txn_id": txn_id,
        "customer_id": customer_id,
        "cruise_id": cruise_id,
        "booking_date": _int_or_none(raw.get("booking_date"), "BOOKING_DATE",
                                     row_no, 19000101, 99991231),
        "outcome": outcome,
        "message_code": message_code,
        "contract_id": _int_or_none(raw.get("contract_id"), "CONTRACT_ID",
                                    row_no, 0, 999999),
        "price": _decimal_or_none(raw.get("price"), "PRICE", row_no),
        "availability_after": _int_or_none(raw.get("availability_after"),
                                           "AVAILABILITY_AFTER", row_no,
                                           0, 9),
    }


def load_hcm_output(path):
    """Load and validate an HCM output file (CSV or JSON) into records."""
    if os.path.getsize(path) > MAX_FILE_BYTES:
        raise LayoutError("HCM output file exceeds the size limit")
    ext = os.path.splitext(path)[1].lower()
    raw_rows = []
    with open(path, "r", encoding="utf-8", newline="") as fh:
        if ext == ".csv":
            reader = csv.reader(fh)
            header = next(reader, None)
            if header != HCM_COLUMNS:
                raise LayoutError(
                    f"CSV header must be exactly {','.join(HCM_COLUMNS)}")
            for row_no, row in enumerate(reader, start=2):
                if not row:
                    continue
                if len(row) != len(HCM_COLUMNS):
                    raise LayoutError(
                        f"row {row_no}: expected {len(HCM_COLUMNS)} columns, "
                        f"got {len(row)}")
                raw_rows.append(dict(zip(JSON_KEYS, row)))
        elif ext == ".json":
            payload = json.load(fh)
            if not isinstance(payload, dict) or "records" not in payload:
                raise LayoutError("JSON must be an object with 'records'")
            if not isinstance(payload["records"], list):
                raise LayoutError("'records' must be a list")
            for row_no, rec in enumerate(payload["records"], start=1):
                if not isinstance(rec, dict):
                    raise LayoutError(f"record {row_no} is not an object")
                unknown = set(rec) - set(JSON_KEYS)
                if unknown:
                    raise LayoutError(
                        f"record {row_no}: unknown keys {sorted(unknown)}")
                raw_rows.append(rec)
        else:
            raise LayoutError("HCM output must be a .csv or .json file")
    if len(raw_rows) > MAX_RECORDS:
        raise LayoutError("HCM output exceeds the record limit")
    records = [_normalise_record(r, i + 1) for i, r in enumerate(raw_rows)]
    seen = set()
    for rec in records:
        if rec["txn_id"] in seen:
            raise LayoutError(f"TXN_ID {rec['txn_id']} occurs more than once")
        seen.add(rec["txn_id"])
    return records


