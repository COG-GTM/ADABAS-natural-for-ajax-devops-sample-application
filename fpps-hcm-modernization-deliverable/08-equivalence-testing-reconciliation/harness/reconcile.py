def run_all(dir_root, decimals=2, tolerance_cents=0):
    """Regenerate every committed artefact under `dir_root`."""
    sample = os.path.join(dir_root, "sample-output")
    fixtures = os.path.join(dir_root, "harness", "fixtures")
    os.makedirs(sample, exist_ok=True)
    expected = lb.generate_expected(decimals)
    lb.dump_json(expected, os.path.join(sample, "legacy-expected.json"))
    write_expected_markdown(expected,
                            os.path.join(sample, "legacy-expected.md"))
    make_fixtures(expected, fixtures, decimals)
    results = {}
    for name in ("clean", "broken"):
        hcm_path = os.path.join(fixtures, f"hcm-output-{name}.csv")
        records = load_hcm_output(hcm_path)
        summary, audit, exceptions = reconcile(expected, records, decimals,
                                               tolerance_cents)
        write_report(os.path.join(sample, name), summary, audit, exceptions,
                     f"harness/fixtures/hcm-output-{name}.csv")
        results[name] = summary
    # The JSON layout must reconcile identically to the CSV layout.
    json_records = load_hcm_output(
        os.path.join(fixtures, "hcm-output-clean.json"))
    json_summary, _, _ = reconcile(expected, json_records, decimals,
                                   tolerance_cents)
    if json_summary != results["clean"]:
        raise RuntimeError("CSV and JSON layouts of the clean fixture do not "
                           "reconcile identically")
    return results


def _tree_files(root):
    out = []
    for base, _, files in os.walk(root):
        for f in files:
            out.append(os.path.relpath(os.path.join(base, f), root))
    return sorted(out)


def check(dir_root, decimals=2, tolerance_cents=0):
    """Regenerate into a temp dir and compare with committed output."""
    tmp = tempfile.mkdtemp(prefix="equivalence-check-")
    try:
        os.makedirs(os.path.join(tmp, "harness"))
        results = run_all(tmp, decimals, tolerance_cents)
        drift = []
        for rel in ("sample-output", os.path.join("harness", "fixtures")):
            fresh_root = os.path.join(tmp, rel)
            committed_root = os.path.join(dir_root, rel)
            fresh = _tree_files(fresh_root)
            committed = (_tree_files(committed_root)
                         if os.path.isdir(committed_root) else [])
            for f in sorted(set(fresh) | set(committed)):
                a = os.path.join(fresh_root, f)
                b = os.path.join(committed_root, f)
                if not (os.path.exists(a) and os.path.exists(b)
                        and filecmp.cmp(a, b, shallow=False)):
                    drift.append(os.path.join(rel, f))
        if results["clean"]["result"] != "RECONCILED":
            drift.append("clean fixture no longer reconciles to zero")
        if results["broken"]["result"] != "EXCEPTIONS":
            drift.append("broken fixture no longer raises exceptions")
        return drift
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if committed sample-output/ or "
                             "harness/fixtures/ differ from a fresh run")
    parser.add_argument("--decimals", type=int, default=2, choices=(2, 3),
                        help="amount precision for comparison (default 2)")
    parser.add_argument("--tolerance-cents", type=int, default=0,
                        help="allowed absolute amount difference in cents "
                             "(default 0: penny-level)")
    sub = parser.add_subparsers(dest="command")
    p_gen = sub.add_parser("generate-expected",
                           help="run the legacy model and write the expected "
                                "batch as JSON")
    p_gen.add_argument("--out", default=EXPECTED_PATH)
    sub.add_parser("make-fixtures",
                   help="write clean and broken HCM output fixtures")
    p_rec = sub.add_parser("reconcile",
                           help="reconcile an HCM output file against the "
                                "expected batch")
    p_rec.add_argument("--expected", default=EXPECTED_PATH)
    p_rec.add_argument("--hcm", required=True,
                       help="HCM output file (.csv or .json)")
    p_rec.add_argument("--out", required=True, help="report directory")
    sub.add_parser("run-all", help="regenerate all committed artefacts")
    args = parser.parse_args(argv)

    if args.tolerance_cents < 0 or args.tolerance_cents > 100_000:
        parser.error("--tolerance-cents must be between 0 and 100000")

    if args.check:
        drift = check(DIR_ROOT, args.decimals, args.tolerance_cents)
        if drift:
            print("DRIFT: committed equivalence output differs from a fresh "
                  "run:", file=sys.stderr)
            for item in drift:
                print(f"  {item}", file=sys.stderr)
            return 1
        print("equivalence harness: committed fixtures and sample-output are "
              "current; clean fixture reconciles to zero, broken fixture "
              "raises exceptions")
        return 0

    if args.command == "generate-expected":
        expected = lb.generate_expected(args.decimals)
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        lb.dump_json(expected, args.out)
        print(f"wrote {args.out}: {expected['control_totals']['record_count']}"
              " records")
        return 0
    if args.command == "make-fixtures":
        expected = lb.generate_expected(args.decimals)
        make_fixtures(expected, FIXTURES_DIR, args.decimals)
        print(f"wrote fixtures to {FIXTURES_DIR}")
        return 0
    if args.command == "reconcile":
        with open(args.expected, "r", encoding="utf-8") as fh:
            expected = json.load(fh)
        try:
            records = load_hcm_output(args.hcm)
        except LayoutError as exc:
            print(f"HCM output rejected: {exc}", file=sys.stderr)
            return 2
        summary, audit, exceptions = reconcile(
            expected, records, args.decimals, args.tolerance_cents)
        write_report(args.out, summary, audit, exceptions,
                     os.path.relpath(args.hcm, DIR_ROOT))
        print(f"{summary['result']}: {summary['exception_count']} "
              f"exception(s); report in {args.out}")
        return 0 if not exceptions else 1
    if args.command == "run-all":
        results = run_all(DIR_ROOT, args.decimals, args.tolerance_cents)
        for name, summary in results.items():
            print(f"{name}: {summary['result']} "
                  f"({summary['exception_count']} exception(s))")
        return 0
    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
