def _expected_to_hcm_rows(expected, decimals):
    rows = []
    for r in _expected_view(expected):
        rows.append({
            "txn_id": r["txn_id"],
            "customer_id": r["customer_id"],
            "cruise_id": r["cruise_id"],
            "booking_date": r["booking_date"],
            "outcome": r["outcome"],
            "message_code": r["message_code"],
            "contract_id": r["contract_id"],
            "price": (str(lb.cents(r["price"], decimals))
                      if r["price"] is not None else None),
            "availability_after": r["availability_after"],
        })
    return rows


def _seed_defects(rows):
    by_id = {r["txn_id"]: r for r in rows}
    by_id["T-0004"]["price"] = "1349.98"
    by_id["T-0018"]["contract_id"] = 500107
    by_id["T-0016"].update({"outcome": lb.ACCEPTED, "message_code": 9800,
                            "contract_id": 500112, "price": "1349.99",
                            "availability_after": 0})
    by_id["T-0011"].update({"outcome": lb.ACCEPTED, "message_code": 9800,
                            "contract_id": 500113, "price": "1290.00",
                            "availability_after": 2})
    return rows


def _write_hcm_csv(path, rows):
    with open(path, "w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(HCM_COLUMNS)
        for r in rows:
            writer.writerow(["" if r[k] is None else r[k] for k in JSON_KEYS])


def make_fixtures(expected, fixtures_dir, decimals):
    os.makedirs(fixtures_dir, exist_ok=True)
    clean = _expected_to_hcm_rows(expected, decimals)
    _write_hcm_csv(os.path.join(fixtures_dir, "hcm-output-clean.csv"), clean)
    lb.dump_json({"batch_id": expected["batch_id"], "records": clean},
                 os.path.join(fixtures_dir, "hcm-output-clean.json"))
    broken = _seed_defects(_expected_to_hcm_rows(expected, decimals))
    _write_hcm_csv(os.path.join(fixtures_dir, "hcm-output-broken.csv"),
                   broken)
    with open(os.path.join(fixtures_dir, "SEEDED-DEFECTS.md"), "w",
              encoding="utf-8") as fh:
        fh.write("# Seeded defects in hcm-output-broken.csv\n\n"
                 "Generated by `harness/reconcile.py make-fixtures`. "
                 "`hcm-output-clean.csv` / `.json` are the legacy expected "
                 "batch rendered in the HCM output layout; the broken file "
                 "is the clean file with these four rows altered.\n\n")
        fh.write(_md_table(["Defect", "Transaction", "Alteration"],
                           [list(d) for d in SEEDED_DEFECTS]))
        fh.write("\n")


