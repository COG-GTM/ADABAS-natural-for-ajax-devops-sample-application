#!/usr/bin/env python3
"""Equivalence reconciliation harness: legacy expected batch vs HCM output.

VALIDATION HARNESS ONLY. This Python compares an HCM's output for a synthetic
transaction batch against the outcomes the legacy Natural logic produces for
the same batch (generated by harness/legacy_batch.py from the behavioural
model in tests/harness/natural_model.py). It is not a re-implementation of
any Natural module and is not a rewrite target; the implementation target is
the HCM configuration the SI builds from directories 02-07.

Usage (run from the repository root):

  python3 <dir>/harness/reconcile.py generate-expected --out FILE.json
  python3 <dir>/harness/reconcile.py make-fixtures
  python3 <dir>/harness/reconcile.py reconcile --expected FILE.json \
          --hcm HCM-OUTPUT.(csv|json) --out REPORT-DIR [--decimals 2] \
          [--tolerance-cents 0]
  python3 <dir>/harness/reconcile.py run-all      # regenerate committed output
  python3 <dir>/harness/reconcile.py --check      # exit 1 if committed output
                                                  # differs from a fresh run

Exit codes: 0 reconciled with zero exceptions (or --check clean);
1 exceptions found (or --check drift); 2 the HCM file failed layout
validation.

HCM output layout (CSV, header row required, columns exactly as listed):

  TXN_ID,CUSTOMER_ID,CRUISE_ID,BOOKING_DATE,OUTCOME,MESSAGE_CODE,
  CONTRACT_ID,PRICE,AVAILABILITY_AFTER

JSON layout: {"batch_id": str, "records": [ {"txn_id", "customer_id",
"cruise_id", "booking_date", "outcome", "message_code", "contract_id",
"price", "availability_after"}, ... ]}. Field rules are in
equivalence-approach.md and enforced by `load_hcm_output`.
"""

