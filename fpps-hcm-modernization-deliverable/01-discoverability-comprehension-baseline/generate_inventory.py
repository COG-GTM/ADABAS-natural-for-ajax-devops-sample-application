def _md_table(headers, rows):
    L = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        L.append("| " + " | ".join(str(c) for c in r) + " |")
    return L


def _code(s):
    return f"`{s}`"


def _fmt_callees(callees):
    if not callees:
        return "—"
    parts = []
    for r in sorted(callees, key=lambda r: (r["line"], r["callee"])):
        parts.append(f"{r['statement']} `{r['callee']}` (L{r['line']})")
    return "; ".join(parts)


def _fmt_access(access):
    if not access:
        return "—"
    return "; ".join(f"`{f}` ({', '.join(v)})" for f, v in sorted(access.items()))


def _exec_loc(v):
    return "n/a" if v is None else str(v)


def _node_id(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def render_inventory(model):
    rows, refs, ct = model["rows"], model["refs"], model["result"]["control_totals"]
    by_lib = defaultdict(list)
    for r in rows:
        by_lib[r["library"]].append(r)

    stmt_counts = defaultdict(int)
    for r in refs:
        stmt_counts[r["statement"]] += 1

    L = [
        "# Module inventory (generated)",
        "",
        GENERATED_BANNER,
        "",
        "> Static inventory of `SunnyIslands/Natural-Libraries/`. Reach status is a *static candidate*"
        " classification (\"unreferenced in analyzed scope\", \"reachable from UI root\"); it does not"
        " prove or disprove runtime use. Maturity: **Demonstrated** — every number below is recomputed"
        " from the shipped sources on each run.",
        "",
        "## Control totals",
        "",
    ]
    type_counts = defaultdict(int)
    for r in rows:
        type_counts[(r["library"], r["type"])] += 1
    L += _md_table(["Measure", "Value"], [
        ("Natural objects (both libraries)", ct["objects"]),
        ("Code objects (subprogram / program / copycode)", ct["code_objects"]),
        ("Static references (CALLNAT / FETCH / INCLUDE / USING)", ct["static_references"]),
        ("… of which CALLNAT", stmt_counts["CALLNAT"]),
        ("… of which FETCH", stmt_counts["FETCH"]),
        ("… of which INCLUDE", stmt_counts["INCLUDE"]),
        ("… of which USING", stmt_counts["USING"]),
        ("Dynamic invocations (`CALLNAT #VAR`, unresolvable statically)", ct["dynamic_invocations"]),
        ("Total source lines (all objects)", sum(r["lines"] for r in rows)),
        ("Executable lines (code objects, comments and blanks removed)",
         sum(r["executable_lines"] or 0 for r in rows if r["type"] in ("subprogram", "program"))),
        ("Objects unreferenced in analyzed scope", ", ".join(_code(o) for o in ct["unreferenced_objects"]) or "none"),
        ("Stand-alone programs with no UI path", ", ".join(_code(o) for o in ct["standalone_programs_no_ui_path"]) or "none"),
    ])
    L += ["", "## Objects per library and type", ""]
    L += _md_table(["Library", "Object type", "Count"],
                   [(lib, t, n) for (lib, t), n in sorted(type_counts.items())])

    for lib in sorted(by_lib):
        L += ["", f"## `{lib}`", ""]
        L += _md_table(
            ["Object", "Type", "LOC", "Exec LOC", "Callers", "Callees (statement `callee` Lline)", "DDM files touched (verbs)", "Reach status"],
            [(
                _code(r["object"]), r["type"], r["lines"], _exec_loc(r["executable_lines"]),
                ", ".join(_code(c) for c in r["callers"]) or "—",
                _fmt_callees(r["callees"]),
                _fmt_access(r["access"]) if r["type"] in ("subprogram", "program") else "—",
                r["status"],
            ) for r in by_lib[lib]],
        )

    L += ["", "## ADABAS files (DDMs) and the code that touches them", ""]
    ddm_rows = []
    for ddm, (fname, db, fnr) in sorted(model["ddm_files"].items()):
        touch = defaultdict(list)
        for r in rows:
            if fname in r["access"]:
                touch[r["object"]] = r["access"][fname]
        ddm_rows.append((
            _code(ddm), _code(fname), db, fnr,
            "; ".join(f"`{o}` ({', '.join(v)})" for o, v in sorted(touch.items())) or "none in analyzed scope",
        ))
    L += _md_table(["DDM object", "ADABAS file", "DB", "FNR", "Accessed by (verbs)"], ddm_rows)

    L += ["", "## Extraction waves (derived from the call graph)", "",
          "Wave = 1 + the longest CALLNAT/FETCH path down to a leaf; leaves are wave 1. Within a wave, read-only"
          " objects precede objects that STORE/UPDATE/DELETE, then alphabetical. Only objects reachable from the"
          " UI root are waved; the remainder are static retirement candidates pending SME confirmation.", ""]
    wave_rows = []
    for w, names in model["waves"]["waves"]:
        for n in names:
            r = next(x for x in rows if x["object"] == n)
            wave_rows.append((w, _code(n), r["type"], r["library"],
                              model["waves"]["writes"][n], _fmt_access(r["access"])))
    L += _md_table(["Wave", "Object", "Type", "Library", "Write verbs", "DDM files touched (verbs)"], wave_rows)
    L += ["", "Outside the waves (static candidates, evidence class: unreferenced in analyzed scope / no UI path):", ""]
    L += [f"- `{n}`" for n in model["waves"]["candidates"]]
    L += ["", "## Source paths", ""]
    L += _md_table(["Object", "Path"], [(_code(r["object"]), _code(r["path"])) for r in rows])
    return "\n".join(L) + "\n"


def render_call_graph(model):
    rows, refs = model["rows"], model["refs"]
    by_name = {r["object"]: r for r in rows}
    L = ["%% Generated by generate_inventory.py — CALLNAT / FETCH / INCLUDE edges (Demonstrated)",
         "flowchart TD",
         '  UI["NJX page rdcruisx.xml<br/>(Demonstrated)"]']
    for lib in ("RDCRUISE", "CRUISE16"):
        L.append(f'  subgraph {lib}["{lib} (Demonstrated)"]')
        for r in rows:
            if r["library"] == lib and r["type"] in CODE_TYPES:
                L.append(f'    {_node_id(r["object"])}["{r["object"]}<br/>{r["type"]}"]')
        L.append("  end")
    L.append("  UI -->|PROCESS PAGE| RDCRUISP")
    grouped = defaultdict(list)
    for r in refs:
        if r["statement"] != "USING":
            grouped[(r["caller"], r["callee"], r["statement"])].append(r["line"])
    for (caller, callee, stmt), lines in sorted(grouped.items(), key=lambda kv: (kv[0][0], min(kv[1]))):
        lines = sorted(lines)
        label = f"{stmt} L{lines[0]}" if len(lines) == 1 else f"{stmt} ×{len(lines)} L" + ",".join(str(n) for n in lines)
        L.append(f'  {_node_id(caller)} -->|{label}| {_node_id(callee)}')
    cands = [r["object"] for r in rows if r["type"] in CODE_TYPES and "unreferenced" in r["status"] or
             r["type"] in CODE_TYPES and "no UI path" in r["status"]]
    L.append("  classDef candidate stroke-dasharray: 5 5,stroke:#b00,color:#b00;")
    if cands:
        L.append("  class " + ",".join(_node_id(c) for c in cands) + " candidate;")
    L.append("  classDef entry fill:#e8f0fe,stroke:#1a56db;")
    L.append("  class RDCRUISP,UI entry;")
    return "\n".join(L) + "\n"


def render_data_access(model):
    rows = model["rows"]
    L = ["%% Generated by generate_inventory.py — code object → ADABAS file (Demonstrated)",
         "flowchart LR"]
    L.append('  subgraph code["Natural code objects with database statements (Demonstrated)"]')
    for r in rows:
        if r["access"]:
            L.append(f'    {_node_id(r["object"])}["{r["object"]}<br/>{r["library"]}"]')
    L.append("  end")
    L.append('  subgraph adabas["ADABAS files — DDMs, DB 12 (Demonstrated)"]')
    for ddm, (fname, db, fnr) in sorted(model["ddm_files"].items()):
        L.append(f'    {_node_id(fname)}[("{fname}<br/>DDM {ddm} · FNR {fnr}")]')
    L.append("  end")
    for r in rows:
        for fname, verbs in sorted(r["access"].items()):
            arrow = "==>" if any(v in DB_WRITE_VERBS for v in verbs) else "-->"
            L.append(f'  {_node_id(r["object"])} {arrow}|{", ".join(verbs)}| {_node_id(fname)}')
    L.append("  classDef candidate stroke-dasharray: 5 5,stroke:#b00,color:#b00;")
    cands = [r["object"] for r in rows if r["access"] and ("unreferenced" in r["status"] or "no UI path" in r["status"])]
    if cands:
        L.append("  class " + ",".join(_node_id(c) for c in cands) + " candidate;")
    return "\n".join(L) + "\n"


def render_architecture(model):
    rows, refs = model["rows"], model["refs"]
    by = defaultdict(list)
    for r in rows:
        by[(r["library"], r["type"])].append(r["object"])
    lib_edges = defaultdict(int)
    for r in refs:
        cl = next(x["library"] for x in rows if x["object"] == r["caller"])
        el = next(x["library"] for x in rows if x["object"] == r["callee"])
        lib_edges[(cl, el, r["statement"])] += 1
    L = ["%% Generated by generate_inventory.py — layered architecture (Demonstrated)",
         "flowchart TB",
         '  browser["Browser / NJX page rdcruisx.xml<br/>27 page events"]'.replace(
             "27", str(model["result"]["control_totals"]["ui_events_declared"])),
         '  subgraph pres["RDCRUISE — presentation library (Demonstrated; ≈ web FPPS presentation layer)"]']
    for t in ("program", "subprogram", "global data area", "local data area"):
        if ("RDCRUISE", t) in by:
            L.append(f'    RD_{_node_id(t)}["{t}s: {", ".join(by[("RDCRUISE", t)])}"]')
    L.append("  end")
    L.append('  subgraph svc["CRUISE16 — business-logic library (Demonstrated; ≈ FPPS core Natural service libraries)"]')
    for t in ("subprogram", "copycode", "parameter data area", "local data area"):
        if ("CRUISE16", t) in by:
            L.append(f'    CR_{_node_id(t)}["{t}s: {", ".join(by[("CRUISE16", t)])}"]')
    L.append("  end")
    L.append('  subgraph data["ADABAS DB 12 (Demonstrated; ≈ FPPS personnel-payroll data model)"]')
    L.append(f'    DDMS[("DDMs: {", ".join(by[("CRUISE16", "DDM")])}")]')
    L.append("  end")
    L.append('  ext["External touch-points<br/>work file CruiseDescriptions.txt · image files · nat: content objects"]')
    L.append("  browser -->|PROCESS PAGE / *PAGE-EVENT| RD_program")
    for (cl, el, st), n in sorted(lib_edges.items()):
        if cl == "RDCRUISE" and el == "CRUISE16":
            L.append(f"  RD_program -->|{st} ×{n}| CR_subprogram")
    L.append("  CR_subprogram -->|READ / FIND / GET / STORE / UPDATE| DDMS")
    L.append("  RD_subprogram -.->|READ WORK / EXPAND XCIOBJECTS| ext")
    return "\n".join(L) + "\n"


def render_diagrams_readme(model, arch, call, data):
    exports = []
    for stem in ("architecture", "call-graph", "data-access"):
        for ext in (".svg", ".png"):
            if (HERE / "diagrams" / f"{stem}{ext}").exists():
                exports.append(f"{stem}{ext}")
    L = ["# Diagrams (generated)", "", GENERATED_BANNER, "",
         "All three diagrams are **Demonstrated**: they are rendered from the analyzer output, not drawn."
         " Dashed red nodes are static candidates (unreferenced in analyzed scope or no UI path); they are"
         " not asserted to be unused at runtime.", ""]
    if exports:
        L += ["Exported images in this directory: " + ", ".join(f"`{e}`" for e in exports) + ".", ""]
    else:
        L += ["No exported images are checked in; render the `.mmd` sources with a Mermaid renderer.", ""]
    L += ["## Architecture (`architecture.mmd`)", "", "```mermaid", arch.rstrip(), "```", "",
          "## Call graph (`call-graph.mmd`)", "", "```mermaid", call.rstrip(), "```", "",
          "## Data-access map (`data-access.mmd`)", "", "```mermaid", data.rstrip(), "```", ""]
    return "\n".join(L)


def _control_totals_block(model):
    rows, ct = model["rows"], model["result"]["control_totals"]
    per_lib = defaultdict(lambda: defaultdict(int))
    for r in rows:
        per_lib[r["library"]][r["type"]] += 1
    L = _md_table(["Measure", "Value"], [
        ("Natural objects in `CRUISE16` + `RDCRUISE`", ct["objects"]),
        ("Code objects (subprogram / program / copycode)", ct["code_objects"]),
        ("Static references (CALLNAT / FETCH / INCLUDE / USING)", ct["static_references"]),
        ("Dynamic invocations (unresolvable statically)", ct["dynamic_invocations"]),
        ("Source lines, all objects", sum(r["lines"] for r in rows)),
        ("Executable lines, programs and subprograms", sum(r["executable_lines"] or 0 for r in rows if r["type"] in ("subprogram", "program"))),
        ("Page events declared in `rdcruisx.xml`", ct["ui_events_declared"]),
        ("Objects unreferenced in analyzed scope", ", ".join(_code(o) for o in ct["unreferenced_objects"]) or "none"),
        ("Stand-alone programs with no UI path", ", ".join(_code(o) for o in ct["standalone_programs_no_ui_path"]) or "none"),
    ])
    L += ["", "| Library | " + " | ".join(t for t in ("program", "subprogram", "copycode", "global data area", "local data area", "parameter data area", "DDM")) + " | Total |",
          "|---|---|---|---|---|---|---|---|---|"]
    for lib in sorted(per_lib):
        counts = [per_lib[lib][t] for t in ("program", "subprogram", "copycode", "global data area", "local data area", "parameter data area", "DDM")]
        L.append(f"| `{lib}` | " + " | ".join(str(c) for c in counts) + f" | {sum(counts)} |")
    return "\n".join(L)


def _waves_block(model):
    rows = {r["object"]: r for r in model["rows"]}
    L = _md_table(["Wave", "Objects (read-only first, then writers)", "Why this order"], [
        (w, ", ".join(f"`{n}`" for n in names),
         "leaf services: no CALLNAT/FETCH out-edges" if w == 1 else
         "calls only objects in earlier waves")
        for w, names in model["waves"]["waves"]])
    L += ["", "Static candidates outside the waves (evidence class in `module-inventory.md`): " +
          ", ".join(f"`{n}` ({rows[n]['status']})" for n in model["waves"]["candidates"]) + "."]
    return "\n".join(L)


def _inject_blocks(text, blocks):
    for name, body in blocks.items():
        start, end = f"<!-- generated:{name} -->", f"<!-- /generated:{name} -->"
        if start not in text or end not in text:
            raise SystemExit(f"discoverability-report.md is missing the {name} marker pair")
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        text = head + start + "\n" + body + "\n" + end + tail
    return text


def render_report(model):
    path = OUTPUTS["discoverability-report.md"]
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    return _inject_blocks(text, {"control-totals": _control_totals_block(model), "waves": _waves_block(model)})


def render_all():
    model = build_model()
