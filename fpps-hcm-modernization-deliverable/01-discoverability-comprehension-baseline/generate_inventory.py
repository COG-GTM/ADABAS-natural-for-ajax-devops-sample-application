from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))

from tools.analyze_disposition import analyze  # noqa: E402
from tests.harness import source_parser as sp  # noqa: E402

CODE_TYPES = ("subprogram", "program", "copycode")
CALL_STATEMENTS = ("CALLNAT", "FETCH")
DB_OPEN_VERBS = ("READ", "FIND", "GET", "HISTOGRAM")
DB_WRITE_VERBS = ("STORE", "UPDATE", "DELETE")
DB_VERBS = DB_OPEN_VERBS + DB_WRITE_VERBS

_LABEL_ONLY = re.compile(r"^\s*([A-Z][A-Z0-9]*)\.\s*$")
_LABEL_INLINE = re.compile(r"^\s*([A-Z][A-Z0-9]*)\.\s+(.*)$")
_LABEL_REF = re.compile(r"\(\s*([A-Z][A-Z0-9]*)\.\s*\)")
_VIEW_DEF = re.compile(r"^\s*1\s+([A-Z0-9@#-]+)\s+VIEW\s+OF\s+([A-Z0-9@#-]+)", re.I)

OUTPUTS = {
    "module-inventory.md": HERE / "module-inventory.md",
    "diagrams/architecture.mmd": HERE / "diagrams" / "architecture.mmd",
    "diagrams/call-graph.mmd": HERE / "diagrams" / "call-graph.mmd",
    "diagrams/data-access.mmd": HERE / "diagrams" / "data-access.mmd",
    "diagrams/README.md": HERE / "diagrams" / "README.md",
    "discoverability-report.md": HERE / "discoverability-report.md",
}

GENERATED_BANNER = (
    "Generated by `python3 fpps-hcm-modernization-deliverable/"
    "01-discoverability-comprehension-baseline/generate_inventory.py` "
    "from `tools/analyze_disposition.py` and `tests/harness/source_parser.py`. "
    "**Do not edit by hand** — run the generator; `--check` fails CI-style if this file drifts."
)


# --------------------------------------------------------------------------
# data-access scan (view names in DB statements, label-aware)
# --------------------------------------------------------------------------
def _view_to_file(inventory):
    """Map every ``VIEW OF`` name declared in the LDAs to its DDM file name."""
    mapping = {}
    for obj in inventory:
        if obj["type"] != "local data area":
            continue
        for line in (REPO / obj["path"]).read_text(encoding="utf-8", errors="replace").splitlines():
            m = _VIEW_DEF.match(line)
            if m:
                mapping[m.group(1).upper()] = m.group(2).upper()
    return mapping


def _ddm_files(inventory):
    """DDM object name -> (ADABAS file name, db, fnr) via the harness DDM parser."""
    out = {}
    for obj in inventory:
        if obj["type"] == "DDM":
            ddm = sp.parse_ddm(REPO / obj["path"])
            out[obj["object"]] = (ddm.file_name, ddm.db, ddm.fnr)
    return out


def _db_access(path, view_to_file):
    """Return {file_name: sorted set of verbs} for one code object.

    Rules (static, conservative):
    * ``READ``/``FIND``/``GET``/``HISTOGRAM`` with a known view on the same
      line open that view; a preceding ``LABEL.`` (own line or inline) binds
      the label to the view.
    * ``STORE viewname`` names the view directly.
    * ``UPDATE (LABEL.)`` / ``DELETE (LABEL.)`` resolve through the label;
      an unlabelled ``UPDATE``/``DELETE`` is attributed to the most recently
      opened view (the innermost active loop in the shipped sources).
    * ``READ WORK`` lines carry no view and are ignored here (work files are
      reported in 06-interface-dependency-mapping instead).
    """
    lines = sp.strip_comments(sp.read_source(path))
    access = defaultdict(set)
    labels = {}
    pending_label = None
    last_view = None
    views = sorted(view_to_file, key=len, reverse=True)
    view_re = re.compile(r"\b(" + "|".join(re.escape(v) for v in views) + r")\b")

    for raw in lines:
        line = raw.upper()
        m = _LABEL_ONLY.match(line)
        if m:
            pending_label = m.group(1)
            continue
        m = _LABEL_INLINE.match(line)
        if m and re.match(r"^(READ|FIND|GET|HISTOGRAM)\b", m.group(2)):
            pending_label = m.group(1)
            line = m.group(2)
        verb_m = re.match(r"^\s*(READ|FIND|GET|HISTOGRAM|STORE|UPDATE|DELETE)\b(.*)$", line)
        if not verb_m:
            continue
        verb, rest = verb_m.group(1), verb_m.group(2)
        if verb == "READ" and re.match(r"^\s*WORK\b", rest):
            continue
        if verb in DB_OPEN_VERBS or verb == "STORE":
            vm = view_re.search(rest)
            if not vm:
                continue
            view = vm.group(1)
            fname = view_to_file[view]
            access[fname].add(verb)
            if verb in DB_OPEN_VERBS:
                last_view = fname
                if pending_label:
                    labels[pending_label] = fname
            pending_label = None
            continue
        # UPDATE / DELETE
        target = None
        lm = _LABEL_REF.search(rest)
        if lm:
            target = labels.get(lm.group(1))
        if target is None:
            vm = view_re.search(rest)
            target = view_to_file[vm.group(1)] if vm else last_view
        if target:
            access[target].add(verb)
    return {k: sorted(v, key=DB_VERBS.index) for k, v in access.items()}


