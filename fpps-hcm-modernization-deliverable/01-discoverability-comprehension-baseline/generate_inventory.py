def build_model():
    result = analyze()
    inventory = sorted(result["inventory"], key=lambda o: (o["library"], o["type"], o["object"]))
    refs = result["references"]
    reach = {r["object"]: r for r in result["reachability"]}
    view_to_file = _view_to_file(inventory)
    ddm_files = _ddm_files(inventory)
    file_to_ddm = {v[0]: k for k, v in ddm_files.items()}

    callers = defaultdict(set)
    callees = defaultdict(list)
    for r in refs:
        callers[r["callee"]].add(r["caller"])
        callees[r["caller"]].append(r)

    access = {}
    for obj in inventory:
        if obj["type"] in ("subprogram", "program"):
            access[obj["object"]] = _db_access(REPO / obj["path"], view_to_file)

    ddm_touched_by = defaultdict(set)
    for obj, files in access.items():
        for fname in files:
            ddm_touched_by[file_to_ddm[fname]].add(obj)

    rows = []
    for obj in inventory:
        name = obj["object"]
        if obj["type"] == "DDM":
            c = sorted(ddm_touched_by[name])
            reach_status = "data file (accessed by " + str(len(c)) + " code objects)" if c else "unreferenced in analyzed scope"
        else:
            c = sorted(callers[name])
            reach_status = reach[name]["status"] if name in reach else "entry point (UI root)"
        rows.append({
            "object": name,
            "type": obj["type"],
            "library": obj["library"],
            "path": obj["path"],
            "lines": obj["lines"],
            "executable_lines": obj["executable_lines"],
            "callers": c,
            "callees": callees.get(name, []),
            "access": access.get(name, {}),
            "status": reach_status,
        })

    return {
        "result": result,
        "rows": rows,
        "refs": refs,
        "ddm_files": ddm_files,
        "file_to_ddm": file_to_ddm,
        "waves": _waves(rows, refs),
    }


def _waves(rows, refs):
    """Leaf-first extraction order over CALLNAT/FETCH edges between code objects.

    wave(x) = 1 + max(wave(callee)) over CALLNAT/FETCH callees; leaves are wave 1.
    Within a wave, read-only objects (no STORE/UPDATE/DELETE) precede writers,
    then alphabetical. Objects unreferenced in the analyzed scope and
    stand-alone programs are listed as candidates outside the waves.
    """
    by_name = {r["object"]: r for r in rows}
    code = {n for n, r in by_name.items() if r["type"] in ("subprogram", "program")}
    out_edges = defaultdict(set)
    for r in refs:
        if r["statement"] in CALL_STATEMENTS and r["caller"] in code and r["callee"] in code:
            out_edges[r["caller"]].add(r["callee"])

    memo = {}

    def wave(n, stack=()):
        if n in memo:
            return memo[n]
        if n in stack:
            return 1
        w = 1 + max((wave(c, stack + (n,)) for c in out_edges[n]), default=0)
        memo[n] = w
        return w

    in_scope = {n for n in code if "reachable" in by_name[n]["status"] or "entry point" in by_name[n]["status"]}
    waves = defaultdict(list)
    for n in in_scope:
        waves[wave(n)].append(n)

    def writes(n):
        return sum(1 for verbs in by_name[n]["access"].values() for v in verbs if v in DB_WRITE_VERBS)

    ordered = []
    for w in sorted(waves):
        ordered.append((w, sorted(waves[w], key=lambda n: (writes(n) > 0, writes(n), n))))
    candidates = sorted(code - in_scope)
    return {"waves": ordered, "candidates": candidates, "writes": {n: writes(n) for n in code}}


