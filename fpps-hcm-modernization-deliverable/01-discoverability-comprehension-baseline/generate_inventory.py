#!/usr/bin/env python3
"""Generate the discoverability baseline artifacts from the Natural sources.

This is a *validation / generation harness* written in Python. It is not part
of any modernization target: it reads the shipped Natural objects through
``tools.analyze_disposition.analyze()`` and ``tests.harness.source_parser`` and
renders Markdown and Mermaid so that no count, edge, or object list in this
directory is hand-typed.

Outputs (all relative to this directory):

* ``module-inventory.md``          every object with type, LOC, executable LOC,
                                   callers, callees, DDM files touched, reach
                                   status, and the derived extraction waves
* ``diagrams/architecture.mmd``    library / layer view
* ``diagrams/call-graph.mmd``      CALLNAT / FETCH / INCLUDE edges
* ``diagrams/data-access.mmd``     code object -> ADABAS file with access verbs
* ``diagrams/README.md``           the same three diagrams embedded in Markdown
* ``discoverability-report.md``    hand-authored narrative; only the blocks
                                   between ``<!-- generated:NAME -->`` and
                                   ``<!-- /generated:NAME -->`` markers are
                                   rewritten (control totals, waves)

Usage::

    python3 fpps-hcm-modernization-deliverable/01-discoverability-comprehension-baseline/generate_inventory.py
    python3 fpps-hcm-modernization-deliverable/01-discoverability-comprehension-baseline/generate_inventory.py --check

``--check`` re-renders in memory and exits 1 if any committed output differs.
"""

