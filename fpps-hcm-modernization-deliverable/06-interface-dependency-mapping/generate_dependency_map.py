# model
# --------------------------------------------------------------------------
def build_model():
    result = analyze()
    inv = {o["object"]: o for o in result["inventory"]}
    refs = sorted(result["references"], key=lambda r: (r["caller"], r["line"], r["callee"]))

    fan_out = defaultdict(lambda: defaultdict(int))
    fan_in = defaultdict(lambda: defaultdict(int))
    for r in refs:
        fan_out[r["caller"]][r["statement"]] += 1
        fan_in[r["callee"]][r["statement"]] += 1

    # external touch-points scanned from executable lines of code objects
    work, content, page = [], [], []
    for name, o in sorted(inv.items()):
        if o["type"] not in CODE_TYPES:
            continue
        for no, code in _numbered_executable_lines(REPO / o["path"]):
            m = _WORK_RE.match(code)
            if m:
                work.append((name, o["path"], no, code.strip()))
            if _XCI_RE.search(code) and not re.match(r"^\s*\d+\s+XCIOBJECTS", code):
                content.append((name, o["path"], no, code.strip()))
            m = _PAGE_RE.match(code)
            if m and not m.group(1).upper().startswith("PROCESS PAGE UPDATE"):
                page.append((name, o["path"], no, code.strip()))

    # NJX event contract: page declarations (xml line) vs adapter handlers (NSP line)
    xml_lines = sp.read_source(UI_XML).splitlines()
    declared = defaultdict(list)
    for no, line in enumerate(xml_lines, 1):
        for m in _XML_METHOD_RE.finditer(line):
            declared[m.group(1)].append(no)
    adapter_path = REPO / inv[UI_ROOT]["path"]
    handlers = {}
    handler_lines = list(_numbered_executable_lines(adapter_path))
    subroutine_calls = defaultdict(list)   # subroutine -> [(callee, statement, line)]
    current_sub = None
    for no, code in handler_lines:
        m = _SUBROUTINE_RE.match(code)
        if m:
            current_sub = m.group(1).upper()
        if re.match(r"^\s*END-SUBROUTINE", code, re.I):
            current_sub = None
        if current_sub:
            for cm in _CALLNAT_RE.finditer(code):
                subroutine_calls[current_sub].append((cm.group(1).upper(), "CALLNAT", no))
            for fm in _FETCH_RE.finditer(code):
                subroutine_calls[current_sub].append((fm.group(1).upper(), "FETCH", no))
    # handler blocks: VALUE U'event' ... until next VALUE / NONE / END-DECIDE
    i = 0
    while i < len(handler_lines):
        no, code = handler_lines[i]
        m = _EVENT_HANDLER_RE.search(code)
        if m and code.strip().upper().startswith("VALUE"):
            event = m.group(1)
            performs, direct = [], []
            j = i + 1
            while j < len(handler_lines):
                n2, c2 = handler_lines[j]
                if re.match(r"^\s*(VALUE\s|NONE\b|END-DECIDE)", c2, re.I):
                    break
                pm = _PERFORM_RE.match(c2)
                if pm:
                    performs.append(pm.group(1).upper())
                for cm in _CALLNAT_RE.finditer(c2):
                    direct.append((cm.group(1).upper(), "CALLNAT", n2))
                for fm in _FETCH_RE.finditer(c2):
                    direct.append((fm.group(1).upper(), "FETCH", n2))
                j += 1
            reached = list(direct)
            for s in performs:
                reached.extend(subroutine_calls.get(s, []))
            handlers[event] = {"line": no, "performs": performs, "reached": reached, "direct": direct}
            i = j
            continue
        i += 1

    events = []
    for ev in sorted(set(declared) | set(handlers)):
        h = handlers.get(ev) or handlers.get("lines." + ev)
        events.append({
            "event": ev,
            "xml_lines": declared.get(ev, []),
            "adapter_line": h["line"] if h else None,
            "performs": h["performs"] if h else [],
            "reached": sorted({(c, s) for c, s, _ in h["reached"]}) if h else [],
            "direct": sorted({(c, s) for c, s, _ in h["direct"]}) if h else [],
        })

    return {
        "result": result, "inv": inv, "refs": refs, "fan_in": fan_in, "fan_out": fan_out,
        "work": work, "content": content, "page": page, "events": events,
        "subroutine_calls": {s: sorted({(c, st) for c, st, _ in v}) for s, v in subroutine_calls.items()},
        "adapter_path": _rel(adapter_path), "xml_path": _rel(UI_XML), "xml_lines": len(xml_lines),
    }


