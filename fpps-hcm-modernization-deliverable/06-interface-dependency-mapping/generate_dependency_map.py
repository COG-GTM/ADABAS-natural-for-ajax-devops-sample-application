#!/usr/bin/env python3
"""Generate the interface and dependency map from the Natural sources.

This is a *validation / generation harness* written in Python. It is not a
modernization target: it reads the shipped Natural objects and the NJX page
through ``tools.analyze_disposition.analyze()`` and
``tests.harness.source_parser`` and renders Markdown and Mermaid so that no
edge, line number, or event name in this directory is hand-typed.

Outputs (relative to this directory):

* ``dependency-map.md``                full edge list (caller, statement,
                                       callee, source line), fan-in / fan-out,
                                       external touch-points (work files,
                                       content objects, NJX event contract)
* ``diagrams/dependency-graph.mmd``    CALLNAT / FETCH / INCLUDE edges (control flow)
* ``diagrams/data-area-usage.mmd``     USING edges (code object -> GDA / LDA / PDA)
* ``diagrams/event-contract.mmd``      NJX page events -> adapter handlers -> services
* ``diagrams/README.md``               the generated diagrams embedded in Markdown

Usage::

    python3 fpps-hcm-modernization-deliverable/06-interface-dependency-mapping/generate_dependency_map.py
    python3 fpps-hcm-modernization-deliverable/06-interface-dependency-mapping/generate_dependency_map.py --check

``--check`` re-renders in memory and exits 1 if any committed output differs.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))

from tools.analyze_disposition import analyze, UI_ROOT, UI_XML  # noqa: E402
from tests.harness import source_parser as sp  # noqa: E402

STATEMENT_ORDER = ("CALLNAT", "FETCH", "INCLUDE", "USING")
CODE_TYPES = ("subprogram", "program", "copycode")

_WORK_RE = re.compile(r"^\s*(DEFINE WORK FILE|READ\s+WORK|CLOSE WORK|WRITE WORK|END-WORK)\b(.*)$", re.I)
_XCI_RE = re.compile(r"XCIOBJECTS")
_PAGE_RE = re.compile(r"^\s*(PROCESS PAGE(?: USING| UPDATE)?|DECIDE ON FIRST \*PAGE-EVENT)\b(.*)$", re.I)
_EVENT_HANDLER_RE = re.compile(r"VALUE\s+U?'((?:[a-z]+\.)?[A-Za-z0-9:.]+)'")
_XML_METHOD_RE = re.compile(r'\b(?:on[a-z]*)?method="(on[A-Za-z0-9]+)"')
_PERFORM_RE = re.compile(r"^\s*PERFORM\s+([A-Z0-9-]+)", re.I)
_SUBROUTINE_RE = re.compile(r"^\s*DEFINE SUBROUTINE\s+([A-Z0-9-]+)", re.I)
_CALLNAT_RE = re.compile(r"CALLNAT\s+['\"]([A-Z0-9-]+)['\"]", re.I)
_FETCH_RE = re.compile(r"FETCH(?:\s+RETURN)?\s+['\"]([A-Z0-9-]+)['\"]", re.I)

OUTPUTS = {
    "dependency-map.md": HERE / "dependency-map.md",
    "diagrams/dependency-graph.mmd": HERE / "diagrams" / "dependency-graph.mmd",
    "diagrams/data-area-usage.mmd": HERE / "diagrams" / "data-area-usage.mmd",
    "diagrams/event-contract.mmd": HERE / "diagrams" / "event-contract.mmd",
    "diagrams/README.md": HERE / "diagrams" / "README.md",
}

GENERATED_BANNER = (
    "Generated by `python3 fpps-hcm-modernization-deliverable/06-interface-dependency-mapping/"
    "generate_dependency_map.py` from `tools/analyze_disposition.py` and `tests/harness/source_parser.py`. "
    "**Do not edit by hand** — run the generator; `--check` fails if this file drifts."
)


def _rel(path):
    return str(Path(path).relative_to(REPO)) if Path(path).is_absolute() else str(path)


def _numbered_executable_lines(path):
    """Yield (line_no, text) for executable lines, preserving original numbering."""
    for no, raw in enumerate(sp.read_source(path).splitlines(), 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("*") or stripped.startswith("/*"):
            continue
        code = re.split(r"/\*", raw)[0].rstrip()
        if code.strip():
            yield no, code


