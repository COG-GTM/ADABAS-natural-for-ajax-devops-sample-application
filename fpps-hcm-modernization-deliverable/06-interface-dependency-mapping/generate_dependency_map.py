def _md_table(headers, rows):
    L = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        L.append("| " + " | ".join(str(c) for c in r) + " |")
    return L


def _c(s):
    return f"`{s}`"


def _nid(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def render_dependency_map(m):
    inv, refs, ct = m["inv"], m["refs"], m["result"]["control_totals"]
    stmt_counts = defaultdict(int)
    for r in refs:
        stmt_counts[r["statement"]] += 1
    L = ["# Dependency map (generated)", "", GENERATED_BANNER, "",
         "> Every edge is a *static literal* reference found in executable source (comments removed)."
         " Dynamic invocations (`CALLNAT #VAR`) are counted separately because static analysis cannot resolve"
         " them. Maturity: **Demonstrated** — regenerated from the shipped sources on each run; nothing here"
         " asserts runtime behaviour.", "",
         "## Edge totals", ""]
    L += _md_table(["Measure", "Value"], [
        ("Static edges (all statement types)", ct["static_references"]),
        *[(f"… {s}", stmt_counts[s]) for s in STATEMENT_ORDER],
        ("Dynamic invocations (unresolvable statically)", ct["dynamic_invocations"]),
        ("Distinct callers", len({r["caller"] for r in refs})),
        ("Distinct callees", len({r["callee"] for r in refs})),
        ("Objects with no inbound edge (unreferenced in analyzed scope)", ", ".join(_c(o) for o in ct["unreferenced_objects"]) or "none"),
        ("Stand-alone programs with no UI path", ", ".join(_c(o) for o in ct["standalone_programs_no_ui_path"]) or "none"),
    ])

    L += ["", "## Full edge list", "",
          "Ordered by caller, then source line. `Callee type` comes from the object inventory; the line is the"
          " physical line in the caller's source file.", ""]
    L += _md_table(["#", "Caller", "Caller library", "Statement", "Callee", "Callee type", "Callee library", "Source line"],
                   [(i, _c(r["caller"]), inv[r["caller"]]["library"], r["statement"], _c(r["callee"]),
                     inv[r["callee"]]["type"], inv[r["callee"]]["library"],
                     _c(f"{inv[r['caller']]['path']}:{r['line']}"))
                    for i, r in enumerate(refs, 1)])

    L += ["", "## Fan-out per caller", ""]
    L += _md_table(["Caller", "Type", *STATEMENT_ORDER, "Total"],
                   [(_c(c), inv[c]["type"], *[m["fan_out"][c][s] for s in STATEMENT_ORDER], sum(m["fan_out"][c].values()))
                    for c in sorted(m["fan_out"])])
    L += ["", "## Fan-in per callee", ""]
    L += _md_table(["Callee", "Type", *STATEMENT_ORDER, "Total", "Distinct callers"],
                   [(_c(c), inv[c]["type"], *[m["fan_in"][c][s] for s in STATEMENT_ORDER], sum(m["fan_in"][c].values()),
                     ", ".join(_c(x) for x in sorted({r["caller"] for r in refs if r["callee"] == c})))
                    for c in sorted(m["fan_in"])])

    L += ["", "## Cross-library edges (RDCRUISE → CRUISE16)", "",
          "These are the only places the presentation library depends on the business-logic library; they are the"
          " service contract an HCM integration layer replaces.", ""]
    L += _md_table(["Caller", "Statement", "Callee", "Callee type", "Source line"],
                   [(_c(r["caller"]), r["statement"], _c(r["callee"]), inv[r["callee"]]["type"],
                     _c(f"{inv[r['caller']]['path']}:{r['line']}"))
                    for r in refs if inv[r["caller"]]["library"] == "RDCRUISE" and inv[r["callee"]]["library"] == "CRUISE16"])

    L += ["", "## External touch-points", "",
          "Everything below leaves the Natural object graph: files on disk, content objects handed to the browser,"
          " and the page contract. Scanned from executable lines only.", "",
          "### Work files", ""]
    L += _md_table(["Object", "Statement (executable line)", "Source line"],
                   [(_c(o), _c(code), _c(f"{p}:{no}")) for o, p, no, code in m["work"]])
    L += ["", "### Content objects (`XCIOBJECTS` → `nat:` URLs)", ""]
    L += _md_table(["Object", "Statement (executable line)", "Source line"],
                   [(_c(o), _c(code), _c(f"{p}:{no}")) for o, p, no, code in m["content"]])
    L += ["", "### Page processing statements", ""]
    L += _md_table(["Object", "Statement (executable line)", "Source line"],
                   [(_c(o), _c(code), _c(f"{p}:{no}")) for o, p, no, code in m["page"]])

    declared_only = [e for e in m["events"] if e["xml_lines"] and e["adapter_line"] is None]
    adapter_only = [e for e in m["events"] if not e["xml_lines"] and e["adapter_line"] is not None]
    both = [e for e in m["events"] if e["xml_lines"] and e["adapter_line"] is not None]
    L += ["", f"### NJX event contract (`{m['xml_path']}` ↔ `{m['adapter_path']}`)", "",
          f"The page ({m['xml_lines']} lines) declares events through `method=\"…\"` attributes; the adapter handles them in a"
          f" `DECIDE ON FIRST *PAGE-EVENT` block. Services reached = literal CALLNAT/FETCH inside the handler block or inside"
          f" the subroutines it PERFORMs.", ""]
    L += _md_table(["Measure", "Value"], [
        ("Events declared in the page", len([e for e in m["events"] if e["xml_lines"]])),
        ("Declared events handled in the adapter", len(both)),
        ("Declared events with no adapter handler", ", ".join(_c(e["event"]) for e in declared_only) or "none"),
        ("Adapter handlers with no page declaration (static candidates)", ", ".join(_c(e["event"]) for e in adapter_only) or "none"),
    ])
    L += ["", "#### Declared events and their handlers", ""]
    L += _md_table(["Event", "Page line(s)", "Adapter handler line", "PERFORMs", "Services reached (statement)"],
                   [(_c(e["event"]), ", ".join(str(n) for n in e["xml_lines"]),
                     e["adapter_line"] if e["adapter_line"] is not None else "—",
                     ", ".join(_c(s) for s in e["performs"]) or "—",
                     ", ".join(f"`{c}` ({s})" for c, s in e["reached"]) or "—")
                    for e in both + declared_only])
    L += ["", "#### Adapter handlers without a page declaration", "",
          "Evidence class: declared in adapter, not raised by any control in the analyzed page. Candidates for retirement"
          " pending SME confirmation; static analysis does not prove they are never raised.", ""]
    L += _md_table(["Handler value", "Adapter line", "PERFORMs", "Services reached (statement)"],
                   [(_c(e["event"]), e["adapter_line"], ", ".join(_c(s) for s in e["performs"]) or "—",
                     ", ".join(f"`{c}` ({s})" for c, s in e["reached"]) or "—") for e in adapter_only])
    return "\n".join(L) + "\n"


def _candidate_class(m, names):
    ct = m["result"]["control_totals"]
    cands = [n for n in names if n in ct["unreferenced_objects"] or n in ct["standalone_programs_no_ui_path"]]
    L = ["  classDef candidate stroke-dasharray: 5 5,stroke:#b00,color:#b00;"]
    if cands:
        L.append("  class " + ",".join(_nid(c) for c in cands) + " candidate;")
    return L


def render_dependency_graph(m):
    inv, refs = m["inv"], m["refs"]
    L = ["%% Generated by generate_dependency_map.py — CALLNAT / FETCH / INCLUDE edges (Demonstrated)", "flowchart LR"]
    shown = []
    for lib in ("RDCRUISE", "CRUISE16"):
        L.append(f'  subgraph {lib}["{lib} (Demonstrated)"]')
        for t in ("program", "subprogram", "copycode"):
            for n, o in sorted(inv.items()):
                if o["library"] == lib and o["type"] == t:
                    shape = ("[[", "]]") if t == "copycode" else ("[", "]")
                    L.append(f'    {_nid(n)}{shape[0]}"{n}<br/>{t}"{shape[1]}')
                    shown.append(n)
        L.append("  end")
    grouped = defaultdict(list)
    for r in refs:
        if r["statement"] != "USING":
            grouped[(r["caller"], r["callee"], r["statement"])].append(r["line"])
    for (caller, callee, stmt), lines in sorted(grouped.items(), key=lambda kv: (kv[0][0], min(kv[1]))):
        lines = sorted(lines)
        label = f"{stmt} L{lines[0]}" if len(lines) == 1 else f"{stmt} ×{len(lines)} L" + ",".join(str(n) for n in lines)
        arrow = "-.-o" if stmt == "INCLUDE" else "-->"
        L.append(f'  {_nid(caller)} {arrow}|{label}| {_nid(callee)}')
    L += _candidate_class(m, shown)
    return "\n".join(L) + "\n"


def render_data_area_usage(m):
    inv, refs = m["inv"], m["refs"]
    L = ["%% Generated by generate_dependency_map.py — USING edges (Demonstrated)", "flowchart LR"]
    callers = sorted({r["caller"] for r in refs if r["statement"] == "USING"})
    areas = [n for n, o in sorted(inv.items(), key=lambda kv: (kv[1]["library"], kv[1]["type"], kv[0]))
             if "data area" in o["type"]]
    L.append('  subgraph code["Code objects (Demonstrated)"]')
    for n in callers:
        L.append(f'    {_nid(n)}["{n}<br/>{inv[n]["library"]}"]')
    L.append("  end")
    for lib in ("RDCRUISE", "CRUISE16"):
        L.append(f'  subgraph {lib}_areas["{lib} data areas (Demonstrated)"]')
        for n in areas:
            if inv[n]["library"] == lib:
                L.append(f'    {_nid(n)}[/"{n}<br/>{inv[n]["type"]}"/]')
        L.append("  end")
    for r in refs:
        if r["statement"] == "USING":
            L.append(f'  {_nid(r["caller"])} -.->|L{r["line"]}| {_nid(r["callee"])}')
    L += _candidate_class(m, callers + areas)
    return "\n".join(L) + "\n"


def render_event_contract(m):
    L = ["%% Generated by generate_dependency_map.py — NJX page events → adapter → services (Demonstrated)",
         "flowchart LR",
         f'  subgraph page["{Path(m["xml_path"]).name} — declared events (Demonstrated)"]']
    for e in m["events"]:
        if e["xml_lines"]:
            L.append(f'    ev_{_nid(e["event"])}(["{e["event"]}"])')
    L.append("  end")
    L.append(f'  subgraph adapter["{UI_ROOT} handlers (Demonstrated)"]')
    subs = sorted({s for e in m["events"] for s in e["performs"]})
    for s in subs:
        L.append(f'    sub_{_nid(s)}["PERFORM {s}"]')
    L.append(f'    direct["inline handler logic"]')
    L.append("  end")
    L.append('  subgraph services["Services reached"]')
    svcs = sorted({c for e in m["events"] for c, _ in e["reached"]})
    for s in svcs:
        L.append(f'    svc_{_nid(s)}["{s}"]')
    L.append("  end")
    for e in m["events"]:
        if not e["xml_lines"] or e["adapter_line"] is None:
            continue
        if e["performs"]:
            for s in e["performs"]:
                L.append(f'  ev_{_nid(e["event"])} -->|L{e["adapter_line"]}| sub_{_nid(s)}')
        elif not e["direct"]:
            L.append(f'  ev_{_nid(e["event"])} -->|L{e["adapter_line"]}| direct')
        for c, st in e["direct"]:
            L.append(f'  ev_{_nid(e["event"])} ==>|{st} inline| svc_{_nid(c)}')
    for s in subs:
        for c, st in m["subroutine_calls"].get(s, []):
            L.append(f'  sub_{_nid(s)} -->|{st}| svc_{_nid(c)}')
    return "\n".join(L) + "\n"


def render_diagrams_readme(m, dep, dau, ev):
    exports = [f"{stem}{ext}" for stem in ("dependency-graph", "data-area-usage", "event-contract") for ext in (".svg", ".png")
               if (HERE / "diagrams" / f"{stem}{ext}").exists()]
    authored = [f"{stem}{ext}" for stem in ("steplib-chain", "environment-promotion", "fpps-interface-model")
                for ext in (".mmd", ".svg", ".png") if (HERE / "diagrams" / f"{stem}{ext}").exists()]
    L = ["# Diagrams (generated)", "", GENERATED_BANNER, "",
         "The three generated diagrams are **Demonstrated** (rendered from analyzer output). Dashed red nodes are static"
         " candidates (unreferenced in analyzed scope or no UI path), not assertions of runtime deadness."
         " Hand-authored diagrams for STEPLIB chaining, environment promotion and the FPPS interface model are"
         " embedded in `../deployment-config.md` and `../fpps-interface-model.md`; their Mermaid source and exports"
         " are copied here as `steplib-chain`, `environment-promotion` and `fpps-interface-model` when a renderer was"
         " available. The FPPS interface model diagram is labelled Roadmap on its right-hand side.", ""]
    if exports:
        L += ["Exported images (generated diagrams): " + ", ".join(f"`{e}`" for e in exports) + ".", ""]
    if authored:
        L += ["Authored diagram files: " + ", ".join(f"`{e}`" for e in authored) + ".", ""]
    L += ["## Dependency graph — CALLNAT / FETCH / INCLUDE (`dependency-graph.mmd`)", "", "```mermaid", dep.rstrip(), "```", "",
          "## Data-area usage — USING (`data-area-usage.mmd`)", "", "```mermaid", dau.rstrip(), "```", "",
          "## NJX event contract (`event-contract.mmd`)", "", "```mermaid", ev.rstrip(), "```", ""]
    return "\n".join(L)


def render_all():
    m = build_model()
    dep = render_dependency_graph(m)
    dau = render_data_area_usage(m)
    ev = render_event_contract(m)
    return {
        "dependency-map.md": render_dependency_map(m),
        "diagrams/dependency-graph.mmd": dep,
        "diagrams/data-area-usage.mmd": dau,
        "diagrams/event-contract.mmd": ev,
        "diagrams/README.md": render_diagrams_readme(m, dep, dau, ev),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if committed outputs differ from a fresh render")
    args = ap.parse_args(argv)
    rendered = render_all()
    if args.check:
        drift = [str(OUTPUTS[k].relative_to(REPO)) for k, t in rendered.items()
                 if not OUTPUTS[k].exists() or OUTPUTS[k].read_text(encoding="utf-8") != t]
        if drift:
            print("DRIFT: regenerate with generate_dependency_map.py:\n  " + "\n  ".join(drift))
            return 1
        print("OK: 06-interface-dependency-mapping generated outputs are current")
        return 0
    for k, t in rendered.items():
        OUTPUTS[k].parent.mkdir(parents=True, exist_ok=True)
        OUTPUTS[k].write_text(t, encoding="utf-8")
        print("wrote", OUTPUTS[k].relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
